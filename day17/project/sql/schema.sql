-- 1. CUSTOMER DIMENSION
CREATE TABLE IF NOT EXISTS dim_customers (
    customer_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id VARCHAR(50) UNIQUE NOT NULL,
    customer_name VARCHAR(100) NOT NULL,
    city VARCHAR(100) NOT NULL
);


-- 2. PRODUCT DIMENSION
CREATE TABLE IF NOT EXISTS dim_products (
    product_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id VARCHAR(50) UNIQUE NOT NULL,
    product_name VARCHAR(100) NOT NULL,
    category VARCHAR(100) NOT NULL
);


-- 3. DATE DIMENSION
CREATE TABLE IF NOT EXISTS dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE UNIQUE NOT NULL,
    day INTEGER NOT NULL,
    month INTEGER NOT NULL,
    month_name VARCHAR(20) NOT NULL,
    quarter INTEGER NOT NULL,
    year INTEGER NOT NULL,
    day_of_week VARCHAR(20) NOT NULL
);


-- 4. SALES FACT TABLE
CREATE TABLE IF NOT EXISTS fact_sales (
    sale_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL,

    customer_key INTEGER NOT NULL,
    product_key INTEGER NOT NULL,

    sale_date DATE NOT NULL,
    date_key INTEGER NOT NULL,

    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),

    CONSTRAINT fact_sales_customer_key_fkey
        FOREIGN KEY (customer_key)
        REFERENCES dim_customers(customer_key),

    CONSTRAINT fact_sales_product_key_fkey
        FOREIGN KEY (product_key)
        REFERENCES dim_products(product_key),

    CONSTRAINT fk_fact_sales_date
        FOREIGN KEY (date_key)
        REFERENCES dim_date(date_key),

    CONSTRAINT uq_fact_sales_order_product
        UNIQUE (order_id, product_key)
);


